export function applyHelplineLocales(countries) {
  for (const country of countries) {
    Object.assign(country.name, NAMES[country.iso] || {});
    if (country.detail) Object.assign(country.detail, ONLY[country.iso] || {});
    for (const service of country.services || []) {
      const extra = DETAILS[`${country.iso}|${service.name}`];
      if (extra && service.detail) Object.assign(service.detail, extra);
    }
  }
  const portugal = countries.find((country) => country.iso === 'PT');
  const sns = portugal?.services?.find((service) => service.name === 'SNS 24');
  if (sns?.parts) Object.assign(sns.parts, snsPartsExtra());
}
